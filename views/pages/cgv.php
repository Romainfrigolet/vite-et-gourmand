    <h1>Conditions générales de vente</h1>
    <p class="text-muted">Applicables à toute commande passée sur le site Vite &amp; Gourmand à compter d'octobre 2026.</p>

    <h2>Article 1 — Objet</h2>
    <p>Les présentes conditions régissent la vente des prestations de traiteur proposées par Vite &amp; Gourmand (préparation et livraison de menus)
       aux clients particuliers et professionnels ayant créé un compte sur le site.</p>

    <h2>Article 2 — Commande</h2>
    <p>La commande s'effectue depuis la fiche d'un menu. Chaque menu précise un nombre minimum de personnes, un délai minimum de commande
       et des conditions particulières (conservation, matériel prêté…) que le client reconnaît avoir lues avant de valider.
       La commande est confirmée par e-mail, puis acceptée par notre équipe. Le nombre de commandes possibles par menu est limité (stock affiché).</p>

    <h2>Article 3 — Prix</h2>
    <p>Les prix sont indiqués en euros toutes taxes comprises. Le prix du menu correspond au prix par personne multiplié par le nombre de convives.
       Une remise de 10 % est accordée pour toute commande comptant au moins 5 personnes de plus que le minimum indiqué pour le menu.</p>

    <h2>Article 4 — Livraison</h2>
    <p>La livraison est gratuite dans la ville de Bordeaux. En dehors de Bordeaux, elle est facturée 5 € majorés de 0,59 € par kilomètre parcouru
       depuis Bordeaux. Le détail du prix (menu, remise, livraison) est affiché avant la validation de la commande.</p>

    <h2>Article 5 — Modification et annulation par le client</h2>
    <p>Tant que la commande n'a pas été acceptée par notre équipe, le client peut la modifier (à l'exception du menu choisi) ou l'annuler sans frais
       depuis son espace. Une fois la commande acceptée, toute demande doit être formulée par téléphone ou via le formulaire de contact.</p>

    <h2>Article 6 — Annulation par Vite &amp; Gourmand</h2>
    <p>En cas d'impossibilité de réaliser la prestation, notre équipe contacte le client par téléphone ou par e-mail avant toute annulation
       et lui en indique le motif.</p>

    <h2>Article 7 — Prêt de matériel</h2>
    <p>Certaines prestations incluent le prêt de matériel (plateaux, présentoirs, caissons isothermes). Le client s'engage à le restituer en bon état
       <strong>dans un délai de 10 jours ouvrés</strong> suivant la prestation, en prenant contact avec la société pour convenir de la restitution.
       <strong>À défaut de restitution dans ce délai, des frais de 600 € seront facturés au client.</strong></p>

    <h2>Article 8 — Hygiène et allergènes</h2>
    <p>Les allergènes présents dans chaque plat sont indiqués sur la fiche du menu. Les consignes de conservation indiquées dans les conditions
       du menu doivent être respectées dès la livraison ; Vite &amp; Gourmand ne saurait être tenu responsable en cas de non-respect de ces consignes.</p>

    <h2>Article 9 — Avis clients</h2>
    <p>À l'issue d'une prestation, le client peut déposer un avis (note de 1 à 5 et commentaire). Les avis sont publiés après modération par notre équipe.</p>

    <h2>Article 10 — Réclamations et médiation</h2>
    <p>Toute réclamation peut être adressée via le formulaire de contact. En cas de litige, le client peut recourir gratuitement à un médiateur de la consommation.</p>
